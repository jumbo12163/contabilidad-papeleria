    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

String sql =
    "SELECT ID_COMPROBANTE, FECHA, OBSERVACIONES, ESTADO "
    + "FROM COMPROBANTE_CONTABLE "
    + "ORDER BY ID_COMPROBANTE DESC";

StringBuilder texto = new StringBuilder();
texto.append("COMPROBANTES CONTABLES\n\n");

try (
    java.sql.Connection conexion = ConexionOracle.conectar();
    java.sql.PreparedStatement sentencia =
        conexion.prepareStatement(sql);
    java.sql.ResultSet resultado = sentencia.executeQuery()
) {
    boolean encontrado = false;

    while (resultado.next()) {
        encontrado = true;

        int id = resultado.getInt("ID_COMPROBANTE");

        texto.append("================================\n");
        texto.append("Comprobante N.º: ").append(id).append("\n");
        texto.append("Fecha: ")
             .append(resultado.getDate("FECHA")).append("\n");
        texto.append("Observaciones: ")
             .append(resultado.getString("OBSERVACIONES")).append("\n");
        texto.append("Estado: ")
             .append(resultado.getString("ESTADO")).append("\n\n");

        String sqlDetalle =
            "SELECT C.CODIGO, C.NOMBRE, D.DEBE, D.HABER "
            + "FROM DETALLE_CONTABLE D "
            + "JOIN CUENTA_CONTABLE C "
            + "ON C.ID_CUENTA = D.ID_CUENTA "
            + "WHERE D.ID_COMPROBANTE = ? "
            + "ORDER BY D.ID_DETALLE";

        double totalDebe = 0;
        double totalHaber = 0;

        try (
            java.sql.PreparedStatement detalle =
                conexion.prepareStatement(sqlDetalle)
        ) {
            detalle.setInt(1, id);

            try (java.sql.ResultSet filas = detalle.executeQuery()) {
                while (filas.next()) {
                    double debe = filas.getDouble("DEBE");
                    double haber = filas.getDouble("HABER");

                    texto.append(filas.getString("CODIGO"))
                         .append(" - ")
                         .append(filas.getString("NOMBRE"))
                         .append("\nDebe: $")
                         .append(String.format("%.2f", debe))
                         .append(" | Haber: $")
                         .append(String.format("%.2f", haber))
                         .append("\n");

                    totalDebe += debe;
                    totalHaber += haber;
                }
            }
        }

        texto.append("\nTotal Debe: $")
             .append(String.format("%.2f", totalDebe));
        texto.append("\nTotal Haber: $")
             .append(String.format("%.2f", totalHaber));
        texto.append("\nDiferencia: $")
             .append(String.format("%.2f", totalDebe - totalHaber));
        texto.append("\n\n");
    }

    if (!encontrado) {
        texto.append("No existen comprobantes registrados.");
    }

    javax.swing.JTextArea area =
        new javax.swing.JTextArea(texto.toString(), 22, 55);
    area.setEditable(false);
    area.setCaretPosition(0);

    javax.swing.JScrollPane desplazamiento =
        new javax.swing.JScrollPane(area);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        desplazamiento,
        "Comprobantes contables",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Error al consultar comprobantes: " + e.getMessage(),
        "Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed

    String[] opciones = {
        "Balance general",
        "Estado de resultados"
    };

    int opcion = javax.swing.JOptionPane.showOptionDialog(
        this,
        "Seleccione el reporte que desea generar:",
        "Reportes contables",
        javax.swing.JOptionPane.DEFAULT_OPTION,
        javax.swing.JOptionPane.QUESTION_MESSAGE,
        null,
        opciones,
        opciones[0]
    );

    if (opcion == -1) {
        return;
    }

    String inicio = javax.swing.JOptionPane.showInputDialog(
        this, "Fecha inicial (AAAA-MM-DD):", "2026-01-01"
    );

    if (inicio == null) return;

    String fin = javax.swing.JOptionPane.showInputDialog(
        this, "Fecha final (AAAA-MM-DD):", "2026-12-31"
    );

    if (fin == null) return;

    try {

        java.sql.Date fechaInicio =
            java.sql.Date.valueOf(inicio.trim());

        java.sql.Date fechaFin =
            java.sql.Date.valueOf(fin.trim());

        if (fechaInicio.after(fechaFin)) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "La fecha inicial no puede ser posterior a la fecha final."
            );
            return;
        }

        // TIPOS DE CUENTA DEL REPORTE
        String tipos;

        if (opcion == 0) {
            tipos = "('ACTIVO', 'PASIVO', 'PATRIMONIO')";
        } else {
            tipos = "('INGRESO', 'EGRESO')";
        }

        // BALANCE GENERAL: ACUMULA HASTA LA FECHA FINAL.
        // ESTADO DE RESULTADOS: UTILIZA EL PERIODO SELECCIONADO.
        String filtroFechas;

        if (opcion == 0) {
            filtroFechas = "AND P.FECHA < ? + 1 ";
        } else {
            filtroFechas = "AND P.FECHA >= ? AND P.FECHA < ? + 1 ";
        }

        String sql =
            "SELECT T.NOMBRE AS TIPO, "
            + "C.CODIGO, "
            + "C.NOMBRE AS CUENTA, "
            + "SUM(D.DEBE) AS TOTAL_DEBE, "
            + "SUM(D.HABER) AS TOTAL_HABER "
            + "FROM DETALLE_CONTABLE D "
            + "JOIN COMPROBANTE_CONTABLE P "
            + "ON P.ID_COMPROBANTE = D.ID_COMPROBANTE "
            + "JOIN CUENTA_CONTABLE C "
            + "ON C.ID_CUENTA = D.ID_CUENTA "
            + "JOIN TIPO_CUENTA T "
            + "ON T.ID_TIPO = C.ID_TIPO "
            + "WHERE P.ESTADO = 'CONTABILIZADO' "
            + filtroFechas
            + "AND T.NOMBRE IN " + tipos + " "
            + "GROUP BY T.NOMBRE, C.CODIGO, C.NOMBRE "
            + "ORDER BY C.CODIGO";

        StringBuilder texto = new StringBuilder();

        texto.append(opcion == 0
            ? "BALANCE GENERAL\n"
            : "ESTADO DE RESULTADOS\n");

        texto.append("Desde: ").append(inicio)
             .append(" Hasta: ").append(fin)
             .append("\n\n");

        double totalActivo = 0;
        double totalPasivo = 0;
        double totalPatrimonio = 0;
        double totalIngresos = 0;
        double totalEgresos = 0;

        // CONSULTAR CUENTAS CONTABLES
        try (
            java.sql.Connection conexion = ConexionOracle.conectar();

            java.sql.PreparedStatement sentencia =
                conexion.prepareStatement(sql)
        ) {

            if (opcion == 0) {
                sentencia.setDate(1, fechaFin);
            } else {
                sentencia.setDate(1, fechaInicio);
                sentencia.setDate(2, fechaFin);
            }

            try (java.sql.ResultSet resultado =
                    sentencia.executeQuery()) {

                boolean encontrado = false;

                while (resultado.next()) {

                    encontrado = true;

                    String tipo = resultado.getString("TIPO");
                    String codigo = resultado.getString("CODIGO");
                    String cuenta = resultado.getString("CUENTA");

                    double debe =
                        resultado.getDouble("TOTAL_DEBE");

                    double haber =
                        resultado.getDouble("TOTAL_HABER");

                    double saldo;

                    if ("ACTIVO".equals(tipo)
                            || "EGRESO".equals(tipo)) {

                        saldo = debe - haber;

                    } else {

                        saldo = haber - debe;
                    }

                    texto.append(codigo)
                         .append(" - ")
                         .append(cuenta)
                         .append(" (")
                         .append(tipo)
                         .append(")\n");

                    texto.append("Saldo: $")
                         .append(String.format("%.2f", saldo))
                         .append("\n\n");

                    switch (tipo) {

                        case "ACTIVO":
                            totalActivo += saldo;
                            break;

                        case "PASIVO":
                            totalPasivo += saldo;
                            break;

                        case "PATRIMONIO":
                            totalPatrimonio += saldo;
                            break;

                        case "INGRESO":
                            totalIngresos += saldo;
                            break;

                        case "EGRESO":
                            totalEgresos += saldo;
                            break;
                    }
                }

                if (!encontrado) {
                    texto.append(
                        "No existen movimientos contabilizados "
                        + "para este reporte y rango de fechas.\n\n"
                    );
                }
            }
        }

        // CALCULAR UTILIDAD DEL EJERCICIO DIRECTAMENTE EN ORACLE
        if (opcion == 0) {

            String sqlUtilidad =
                "SELECT NVL(SUM(CASE "
                + "WHEN T.NOMBRE = 'INGRESO' "
                + "THEN D.HABER - D.DEBE "
                + "WHEN T.NOMBRE = 'EGRESO' "
                + "THEN D.DEBE - D.HABER "
                + "ELSE 0 END), 0) AS UTILIDAD "
                + "FROM DETALLE_CONTABLE D "
                + "JOIN COMPROBANTE_CONTABLE P "
                + "ON P.ID_COMPROBANTE = D.ID_COMPROBANTE "
                + "JOIN CUENTA_CONTABLE C "
                + "ON C.ID_CUENTA = D.ID_CUENTA "
                + "JOIN TIPO_CUENTA T "
                + "ON T.ID_TIPO = C.ID_TIPO "
                + "WHERE P.ESTADO = 'CONTABILIZADO' "
                + "AND P.FECHA >= ? "
                + "AND P.FECHA < ? + 1 "
                + "AND T.NOMBRE IN ('INGRESO', 'EGRESO')";

            double utilidadEjercicio = 0;

            try (
                java.sql.Connection conexionUtilidad =
                    ConexionOracle.conectar();

                java.sql.PreparedStatement ps =
                    conexionUtilidad.prepareStatement(sqlUtilidad)
            ) {

                ps.setDate(1, fechaInicio);
                ps.setDate(2, fechaFin);

                try (java.sql.ResultSet rs = ps.executeQuery()) {

                    if (rs.next()) {
                        utilidadEjercicio =
                            rs.getDouble("UTILIDAD");
                    }
                }
            }

            texto.append("UTILIDAD DEL EJERCICIO\n");

            texto.append(String.format(
                "Resultado del período: $%.2f%n%n",
                utilidadEjercicio
            ));

            // SUMAR LA UTILIDAD UNA SOLA VEZ AL PATRIMONIO
            totalPatrimonio += utilidadEjercicio;
        }

        // MOSTRAR TOTALES
        texto.append("\n========== TOTALES ==========\n");

        if (opcion == 0) {

            texto.append(String.format(
                "Total Activo: $%.2f%n",
                totalActivo
            ));

            texto.append(String.format(
                "Total Pasivo: $%.2f%n",
                totalPasivo
            ));

            texto.append(String.format(
                "Total Patrimonio: $%.2f%n",
                totalPatrimonio
            ));

            texto.append(String.format(
                "Pasivo + Patrimonio: $%.2f%n",
                totalPasivo + totalPatrimonio
            ));

            texto.append(String.format(
                "Diferencia del balance: $%.2f%n",
                totalActivo - totalPasivo - totalPatrimonio
            ));

        } else {

            texto.append(String.format(
                "Total Ingresos: $%.2f%n",
                totalIngresos
            ));

            texto.append(String.format(
                "Total Egresos: $%.2f%n",
                totalEgresos
            ));

            texto.append(String.format(
                "Utilidad / Pérdida: $%.2f%n",
                totalIngresos - totalEgresos
            ));
        }

        // VENTANA DEL REPORTE
        javax.swing.JTextArea area =
            new javax.swing.JTextArea(texto.toString(), 25, 55);

        area.setEditable(false);
        area.setCaretPosition(0);

        javax.swing.JOptionPane.showMessageDialog(
            this,
            new javax.swing.JScrollPane(area),
            "Reporte contable",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Fecha inválida. Utilice el formato AAAA-MM-DD.",
            "Validación de fechas",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error al generar el reporte: " + e.getMessage(),
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_jButton4ActionPerformed

