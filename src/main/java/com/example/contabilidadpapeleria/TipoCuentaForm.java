private void cargarTiposCuenta() {

    DefaultTableModel modelo =
        (DefaultTableModel) tblTiposCuenta.getModel();

    modelo.setRowCount(0);

    String sql = "SELECT ID_TIPO, NOMBRE, DESCRIPCION "
               + "FROM TIPO_CUENTA ORDER BY ID_TIPO";

    try (Connection conexion = ConexionOracle.conectar();
         PreparedStatement ps = conexion.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {

            modelo.addRow(new Object[]{
                rs.getInt("ID_TIPO"),
                rs.getString("NOMBRE"),
                rs.getString("DESCRIPCION")
            });
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error al consultar: " + e.getMessage()
        );
    }
}
    
