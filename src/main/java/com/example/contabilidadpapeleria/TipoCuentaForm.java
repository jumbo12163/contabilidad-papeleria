    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
String nombre = txtNombre.getText().trim();
String descripcion = txtDescripcion.getText().trim();

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese el nombre del tipo de cuenta.");
    txtNombre.requestFocus();
    return;
}

if (descripcion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese la descripción.");
    txtDescripcion.requestFocus();
    return;
}

if (nombre.length() > 50 || descripcion.length() > 200) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "El nombre admite máximo 50 caracteres y la descripción 200.");
    return;
}

String sql = "INSERT INTO TIPO_CUENTA (NOMBRE, DESCRIPCION) "
           + "VALUES (?, ?)";

try (java.sql.Connection conexion = ConexionOracle.conectar();
     java.sql.PreparedStatement ps = conexion.prepareStatement(sql)) {

    ps.setString(1, nombre);
    ps.setString(2, descripcion);

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Tipo de cuenta guardado correctamente.");

    txtIdTipo.setText("");
    txtNombre.setText("");
    txtDescripcion.setText("");

    cargarTiposCuenta();

    btnModificar.setEnabled(false);
    btnEliminar.setEnabled(false);

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Error al guardar: " + e.getMessage(),
        "Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
int fila = tblTiposCuenta.getSelectedRow();

if (fila == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Seleccione un tipo de cuenta de la tabla.");
    return;
}

int filaModelo = tblTiposCuenta.convertRowIndexToModel(fila);

int idTipo = Integer.parseInt(
    tblTiposCuenta.getModel().getValueAt(filaModelo, 0).toString()
);

String nombre = txtNombre.getText().trim();
String descripcion = txtDescripcion.getText().trim();

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese el nombre.");
    return;
}

if (descripcion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese la descripción.");
    return;
}

if (nombre.length() > 50 || descripcion.length() > 200) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "El nombre admite 50 caracteres y la descripción 200.");
    return;
}

String sql = "UPDATE TIPO_CUENTA "
           + "SET NOMBRE = ?, DESCRIPCION = ? "
           + "WHERE ID_TIPO = ?";

try (java.sql.Connection conexion = ConexionOracle.conectar();
     java.sql.PreparedStatement ps = conexion.prepareStatement(sql)) {

    ps.setString(1, nombre);
    ps.setString(2, descripcion);
    ps.setInt(3, idTipo);

    int resultado = ps.executeUpdate();

    if (resultado > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Tipo de cuenta modificado correctamente.");

        txtIdTipo.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");

        cargarTiposCuenta();

        btnModificar.setEnabled(false);
        btnEliminar.setEnabled(false);

    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "No se encontró el registro.");
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Error al modificar: " + e.getMessage(),
        "Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
if (txtIdTipo.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Seleccione un registro para eliminar.");
    return;
}

int confirmar = JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar este tipo de cuenta?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
);

if (confirmar != JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM TIPO_CUENTA WHERE ID_TIPO = ?";

try (Connection conexion = ConexionOracle.conectar();
     PreparedStatement ps = conexion.prepareStatement(sql)) {

    ps.setInt(1, Integer.parseInt(txtIdTipo.getText()));

    int filas = ps.executeUpdate();

    if (filas > 0) {
        JOptionPane.showMessageDialog(this,
                "Registro eliminado correctamente.");

        txtIdTipo.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");

        cargarTiposCuenta();

        btnModificar.setEnabled(false);
        btnEliminar.setEnabled(false);

    } else {
        JOptionPane.showMessageDialog(this,
                "No se encontró el registro.");
    }

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error al eliminar: " + e.getMessage());
}
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String nombre = txtNombre.getText().trim();

if (nombre.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingrese el nombre de la cuenta que desea buscar.");
    txtNombre.requestFocus();
    return;
}

String sql = "SELECT ID_TIPO, NOMBRE, DESCRIPCION "
           + "FROM TIPO_CUENTA "
           + "WHERE UPPER(NOMBRE) LIKE UPPER(?)";

try (Connection conexion = ConexionOracle.conectar();
     PreparedStatement ps = conexion.prepareStatement(sql)) {

    ps.setString(1, "%" + nombre + "%");

    try (ResultSet rs = ps.executeQuery()) {

        if (rs.next()) {
            txtIdTipo.setText(String.valueOf(rs.getInt("ID_TIPO")));
            txtNombre.setText(rs.getString("NOMBRE"));
            txtDescripcion.setText(rs.getString("DESCRIPCION"));

            JOptionPane.showMessageDialog(this, "Registro encontrado.");
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el registro.");
        }
    }

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage());
}    }//GEN-LAST:event_btnBuscarActionPerformed

