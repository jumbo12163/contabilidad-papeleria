private void cargarTiposCuenta() {
    cboTipo.removeAllItems();

    String sql = "SELECT NOMBRE FROM TIPO_CUENTA ORDER BY ID_TIPO";

    try (java.sql.Connection conexion = ConexionOracle.conectar();
         java.sql.PreparedStatement ps = conexion.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            cboTipo.addItem(rs.getString("NOMBRE"));
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error al cargar tipos: " + e.getMessage()
        );
    }
}

private void cargarCuentas() {

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tblCuentas.getModel();

    modelo.setRowCount(0);

    String sql = "SELECT C.ID_CUENTA, C.CODIGO, C.NOMBRE, T.NOMBRE AS TIPO "
            + "FROM CUENTA_CONTABLE C "
            + "INNER JOIN TIPO_CUENTA T ON C.ID_TIPO = T.ID_TIPO "
            + "ORDER BY C.ID_CUENTA";

    try (java.sql.Connection conexion = ConexionOracle.conectar();
         java.sql.PreparedStatement ps = conexion.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("ID_CUENTA"),
                rs.getString("CODIGO"),
                rs.getString("NOMBRE"),
                rs.getString("TIPO")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Error al cargar cuentas: " + e.getMessage());
    }
}

